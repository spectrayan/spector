# ---------------------------------------------------------------------------
# Gemini API Caller
# ---------------------------------------------------------------------------
def call_gemini(prompt, max_retries=6, temperature=TEMPERATURE):
    """Call Gemini-3.1-Flash-Lite and return parsed JSON response."""
    url = f"https://generativelanguage.googleapis.com/v1beta/models/{MODEL}:generateContent?key={GEMINI_API_KEY}"

    payload = json.dumps({
        "contents": [{"role": "user", "parts": [{"text": prompt}]}],
        "generationConfig": {
            "temperature": temperature,
            "maxOutputTokens": 8192,
            "responseMimeType": "application/json"
        }
    }).encode("utf-8")

    for attempt in range(max_retries):
        req = urllib.request.Request(url, data=payload, headers={"Content-Type": "application/json"})
        try:
            with urllib.request.urlopen(req, context=SSL_CTX, timeout=60) as resp:
                data = json.loads(resp.read().decode("utf-8"))
                candidates = data.get("candidates", [])
                if candidates and "content" in candidates[0]:
                    txt = candidates[0]["content"]["parts"][0]["text"]
                    return json.loads(txt)
                else:
                    reason = candidates[0].get("finishReason", "UNKNOWN") if candidates else "NO_CANDIDATES"
                    print(f"  Empty response (attempt {attempt+1}): {reason}")
        except json.JSONDecodeError as e:
            print(f"  JSON parse error (attempt {attempt+1}): {e}")
            time.sleep(1)
        except urllib.error.HTTPError as e:
            body = e.read().decode("utf-8", errors="ignore")[:300]
            if e.code == 429:
                wait = (attempt + 1) * 5
                print(f"  Rate limited (429), backing off {wait}s...")
                time.sleep(wait)
            elif e.code == 503:
                wait = (attempt + 1) * 3
                print(f"  Server overloaded (503), retrying in {wait}s...")
                time.sleep(wait)
            else:
                print(f"  HTTP {e.code}: {body}")
                time.sleep(2)
        except Exception as e:
            print(f"  API error (attempt {attempt+1}): {e}")
            time.sleep(2)

    print(f"  FAILED after {max_retries} retries. Returning empty list.")
    return []

