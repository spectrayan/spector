def generate_biographical_phase(phase, batch_size=50):
    """Generate 500 memories for a single life phase via Gemini, in batches of 50."""
    phase_id = phase["id"]
    label = phase["label"]
    yr_start, yr_end = phase["years"]
    context = phase["prompt_context"]
    output_file = DATASET_DIR / f"corpus-bio-{phase_id}.jsonl"

    print(f"\n{'='*70}")
    print(f"  BIOGRAPHICAL PHASE: {label}")
    print(f"  Output: {output_file}")
    print(f"{'='*70}")

    all_records = []
    num_batches = 10  # 10 batches  50 = 500

    for batch_idx in range(num_batches):
        batch_num = batch_idx + 1
        year_focus_start = yr_start + (yr_end - yr_start) * batch_idx // num_batches
        year_focus_end = yr_start + (yr_end - yr_start) * (batch_idx + 1) // num_batches

        prompt = f"""You are generating authentic autobiographical memories for a person named Mike Thompson.
These are memories from the perspective of an adult looking back on this period of his life,
as if he were telling his AI companion Jarvis about them.

LIFE PHASE: {label}
YEAR FOCUS FOR THIS BATCH: {year_focus_start} to {year_focus_end}

DETAILED CONTEXT:
{context}

CRITICAL RULES:
1. Generate exactly {batch_size} distinct memories as a JSON array.
2. Each memory is a natural conversational exchange  Mike telling Jarvis about a memory,
   and Jarvis responding. These should feel like real conversations, not database entries.
3. VARY the emotional tone: some memories are joyful, some embarrassing, some mundane,
   some bittersweet, some traumatic, some funny, some boring.
4. VARY the length: some are 8 words ("Remember that dog we had? Bruno?"), some are
   80 words (a full story about a specific day).
5. Include SPECIFIC details that make memories feel real: brand names, exact dates,
   weather, what someone was wearing, the song playing, the smell of something.
6. Some memories should be FRAGMENTARY  "I think it was a Tuesday? Or maybe Wednesday.
   We were at Grandpa Arthur's and he was telling that story about the bridge in France..."
7. Some should reference OTHER memories: "This was right after Emily broke her arm, remember?"
8. Jarvis's responses should vary: sometimes empathetic, sometimes factual, sometimes
   asking a follow-up question, sometimes brief ("I remember that well.").
9. DO NOT use the same opening pattern for multiple memories. No "I remember when..." for
   every single one.
10. Include at least 5 memories that are SENSORY (sounds, smells, textures, tastes) rather
    than narrative.

Return JSON array:
[
  {{
    "year": 1994,
    "month": 7,
    "day": 15,
    "hour": 14,
    "userText": "...",
    "jarvisText": "...",
    "synapticTags": ["childhood", "summer", "swimming"],
    "valence": 75,
    "importance": 3.5,
    "arousal": 90
  }}
]
"""
        print(f"  Batch {batch_num}/{num_batches} (years {year_focus_start}-{year_focus_end})...", end=" ", flush=True)
        result = call_gemini(prompt)

        if not result:
            print(f"EMPTY  skipping batch {batch_num}")
            continue

        batch_records = []
        for item in result:
            try:
                yr = max(yr_start, min(yr_end, int(item.get("year", yr_start))))
                mo = max(1, min(12, int(item.get("month", 6))))
                dy = max(1, min(28, int(item.get("day", 15))))
                hr = max(0, min(23, int(item.get("hour", 14))))
                dt = datetime.datetime(yr, mo, dy, hr, 0)

                rec_id = f"bio-{phase_id}-{len(all_records)+len(batch_records)+1:04d}"
                sess_id = f"session-bio-{dt.strftime('%Y%m%d')}-{random.randint(1,99):02d}"
                u_text = item.get("userText", "")
                j_text = item.get("jarvisText", "")
                tags = item.get("synapticTags", [phase_id, "biographical"])

                if not u_text:
                    continue

                # User turn
                batch_records.append({
                    "id": rec_id,
                    "text": u_text,
                    "synapticTags": tags,
                    "valence": int(item.get("valence", 30)),
                    "importance": float(item.get("importance", 3.0)),
                    "arousal": int(item.get("arousal", 60)),
                    "sessionId": sess_id,
                    "timestampMs": to_epoch_ms(dt),
                    "entityMentions": detect_entities(u_text),
                    "memoryType": "EPISODIC",
                    "agentRecallCount": 0,
                })

                # Jarvis turn
                if j_text:
                    batch_records.append({
                        "id": f"{rec_id}-j",
                        "text": j_text,
                        "synapticTags": tags,
                        "valence": int(item.get("valence", 30) * 0.5),
                        "importance": round(float(item.get("importance", 3.0)) * 0.85, 2),
                        "arousal": int(item.get("arousal", 60) * 0.4),
                        "sessionId": sess_id,
                        "timestampMs": to_epoch_ms(dt + datetime.timedelta(seconds=30)),
                        "entityMentions": detect_entities(j_text),
                        "memoryType": "SEMANTIC",
                        "agentRecallCount": 0,
                    })
            except Exception as e:
                print(f"  [skip record: {e}]", end="")
                continue

        all_records.extend(batch_records)
        print(f"{len(batch_records)} records")
        time.sleep(0.5)  # Gentle rate limiting

    # Write output
    with open(output_file, "w", encoding="utf-8") as f:
        for r in all_records:
            f.write(json.dumps(r) + "\n")

    print(f"   Phase '{label}' complete: {len(all_records)} records  {output_file.name}")
    return len(all_records)


