def rebuild_master_corpus():
    """Concatenate all biographical + daily files into corpus.jsonl."""
    print("\n" + "=" * 70)
    print("  REBUILDING MASTER CORPUS")
    print("=" * 70)

    all_records = []

    # Load biographical files
    for bio_file in sorted(DATASET_DIR.glob("corpus-bio-*.jsonl")):
        with open(bio_file, "r", encoding="utf-8") as f:
            for line in f:
                if line.strip():
                    all_records.append(json.loads(line))
        print(f"  Loaded {bio_file.name}")

    # Load daily files
    for day_file in sorted(DAILY_DIR.glob("corpus-day-*.jsonl")):
        with open(day_file, "r", encoding="utf-8") as f:
            for line in f:
                if line.strip():
                    all_records.append(json.loads(line))

    # Sort by timestamp
    all_records.sort(key=lambda r: r.get("timestampMs", 0))

    # Write master corpus
    master_file = DATASET_DIR / "corpus.jsonl"
    with open(master_file, "w", encoding="utf-8") as f:
        for r in all_records:
            f.write(json.dumps(r) + "\n")

    print(f"\n   Master corpus rebuilt: {len(all_records)} total records  corpus.jsonl")
    return len(all_records)


